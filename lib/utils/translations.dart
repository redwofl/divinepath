  /// Get a translated string by key for the given locale code.
  /// Falls back to English if translation not found.
  static String get(String key, {String locale = 'en'}) {
    return _strings[locale]?[key] ?? _strings['en']?[key] ?? key;
  }

  /// Get a translated string with placeholder replacement.
  /// Example: t('chanted_times', {'count': '5'}) => "Chanted 5 times"
  static String t(String key,
      {String locale = 'en', Map<String, String>? params}) {
    String text = get(key, locale: locale);
    if (params != null) {
      params.forEach((k, v) {
        text = text.replaceAll('{$k}', v);
      });
    }
    return text;
  }

  /// Total number of localized daily wisdom quotes.
  static const int dailyQuoteCount = 10;

  /// Get the daily wisdom quote for a given day, localized to [locale].
  /// Falls back to English if the translation for [locale] is missing.
  static String getDailyQuote(int day, {String locale = 'en'}) {
    final index = day % dailyQuoteCount;
    return get('daily_quote_$index', locale: locale);
  }

  /// Get all supported locales
  static const List<Map<String, String>> supportedLocales = [
    {'code': 'en', 'name': 'English', 'native': 'English', 'badge': 'EN'},
    {'code': 'hi', 'name': 'Hindi', 'native': 'हिन्दी', 'badge': 'हि'},
    {'code': 'mr', 'name': 'Marathi', 'native': 'मराठी', 'badge': 'म्र'},
    {'code': 'gu', 'name': 'Gujarati', 'native': 'ગુજરાતી', 'badge': 'ગુ'},
  ];

  /// Get badge text for a locale code
  static String getBadge(String code) {
    for (final locale in supportedLocales) {
      if (locale['code'] == code) return locale['badge'] ?? code.toUpperCase();
    }
    return code.toUpperCase();
  }

  /// Get native name for a locale code
  static String getNativeName(String code) {
    for (final locale in supportedLocales) {
      if (locale['code'] == code) return locale['native'] ?? code;
    }
    return code;
  }
