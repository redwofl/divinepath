  /// Get badge text for a locale code
  static String getBadge(String code) {
    for (final locale in supportedLocales) {
      if (locale['code'] == code) return locale['badge'] ?? code.toUpperCase();
    }
    return code.toUpperCase();
  }

  /// Get native name for a locale code
  static String getNativeName(String code) {
    for (final locale in supportedLocales) {
      if (locale['code'] == code) return locale['native'] ?? code;
    }
    return code;
  }
